-- Quartier générique de chaque commune hors Conakry (le nom d'un quartier est unique dans toute la base : on ajoute la préfecture
-- quand deux communes portent le même nom).
insert into public.neighborhoods (nom, commune_id, actif, generique)
select
  case when c.nom like '% Centre' then c.nom else 'Centre de ' || c.nom end
    || case when count(*) over (partition by c.nom) > 1 then ' (' || p.nom || ')' else '' end,
  c.id, true, true
from public.communes c
join public.prefectures p on p.id = c.prefecture_id
where c.ville_id is null
  and not exists (select 1 from public.neighborhoods n where n.commune_id = c.id and n.generique);
